#!/usr/bin/env python3
"""Assemble and self-check the V98 candidate: frozen V92 + the extra-cow route.

Run from repo root:
    .venv/bin/python experiments/v98_economics/build.py
"""

from __future__ import annotations

import base64
import hashlib
import importlib.util
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
V92 = ROOT / "experiments/v92_overflow_guard/candidate.py"
OVERLAY = HERE / "candidate_overlay.py"
OUT = HERE / "candidate.py"
failures: list[str] = []


def check(name, ok, detail=""):
    print(f"[{'PASS' if ok else 'FAIL'}] {name}{(' :: ' + detail) if detail else ''}")
    if not ok:
        failures.append(name)


def main():
    v92_text = V92.read_text()
    overlay_text = OVERLAY.read_text()
    marker = "def _v98_entrypoint(obs, configuration=None):"
    idx = overlay_text.index(marker)
    b64 = base64.b64encode(v92_text.encode()).decode()
    literal = "\n".join(f'    "{b64[i:i + 76]}"' for i in range(0, len(b64), 76))
    OUT.write_text("# V98 candidate: frozen V92 (embedded verbatim) + extra-cow route.\n"
                   "# Generated by experiments/v98_economics/build.py. Do not hand-edit.\n"
                   "import base64 as _v98_b64\n\n"
                   f"_V92_SOURCE_B64 = (\n{literal}\n)\n\n"
                   + v92_text + "\n\n" + overlay_text[:idx] + overlay_text[idx:])
    digest = hashlib.sha256(OUT.read_bytes()).hexdigest()
    print(f"wrote {OUT}  sha256 {digest}\n")

    dec = base64.b64decode("".join(
        p.strip().strip('"')
        for p in OUT.read_text().split("_V92_SOURCE_B64 = (")[1].split(")")[0].splitlines()
    )).decode()
    check("embedded V92 byte-identical", dec == v92_text,
          hashlib.sha256(v92_text.encode()).hexdigest()[:16])

    spec = importlib.util.spec_from_file_location("v98", OUT)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    check("module loads with an entrypoint", callable(getattr(mod, "_kaggle_submission_entrypoint", None)))

    from kaggle_environments.agent import get_last_callable
    bound = get_last_callable(OUT.read_text(), None, str(OUT))
    check("loader binds the V98 entrypoint", getattr(bound, "__name__", "") == "_v98_entrypoint",
          getattr(bound, "__name__", ""))

    def tiles(with_pasture=True, cow_shed=False):
        t = [[None] * 10 for _ in range(10)]
        if with_pasture:
            t[3][3] = {"kind": "PASTURE"}
        return t

    def obs(day, money, tl, shed=None):
        farm = {"money": money, "farmer": [0, 0], "hands": [], "tiles": tl,
                "unlocked_quadrants": ["NW"], "hires_today": 0}
        s = {"COW": 0, "SHEEP": 0, "WHEAT": 0}
        s.update(shed or {})
        return {"day": day, "hour": 5, "player": 0, "step": day * 24 + 5,
                "market": {"prices": {"COW": 400}},
                "private": {"shed": s, "seeds": {}, "inventories": [{}]},
                "farms": [farm]}

    act = {"farmer": ["PASS"], "hands": [], "market": [["SELL", "WOOL", 2]]}

    a = mod._v98_apply(obs(6, 910, tiles()), act)
    check("day 6, cash, free pasture -> BUY_ANIMAL COW appended",
          ["BUY_ANIMAL", "COW", 1] in a["market"], json.dumps(a["market"]))
    check("existing SELL order preserved", ["SELL", "WOOL", 2] in a["market"])
    check("input action not mutated", act["market"] == [["SELL", "WOOL", 2]])

    a = mod._v98_apply(obs(6, 700, tiles()), act)
    check("cash below the floor -> no purchase", "BUY_ANIMAL" not in json.dumps(a["market"]))

    a = mod._v98_apply(obs(6, 910, tiles(with_pasture=False)), act)
    check("no free pasture -> no purchase", "BUY_ANIMAL" not in json.dumps(a["market"]))

    a = mod._v98_apply(obs(6, 910, tiles(), shed={"COW": 1}), act)
    check("a cow already waiting in the shed -> no second purchase",
          "BUY_ANIMAL" not in json.dumps(a["market"]))

    a = mod._v98_apply(obs(5, 910, tiles()), act)
    check("wrong day -> no purchase", "BUY_ANIMAL" not in json.dumps(a["market"]))

    full = {"farmer": ["PASS"], "hands": [],
            "market": [["SELL", "WHEAT", 1]] * 10}
    a = mod._v98_apply(obs(6, 910, tiles()), full)
    check("market list already at maxMarketOrdersPerTurn -> no purchase",
          "BUY_ANIMAL" not in json.dumps(a["market"]), json.dumps(a["market"])[:60])

    busy = {"farmer": ["PASS"], "hands": [],
            "market": [["SELL", "WOOL", 2], ["BUY_ANIMAL", "SHEEP", 1]]}
    a = mod._v98_apply(obs(6, 910, tiles()), busy)
    check("tape already buying an animal this turn -> no second purchase",
          sum(1 for o in a["market"] if o[0] == "BUY_ANIMAL") == 1)

    (HERE / "candidate_build.json").write_text(json.dumps({
        "candidate": str(OUT), "sha256": digest,
        "v92_file_sha256": hashlib.sha256(V92.read_bytes()).hexdigest(),
        "overlay_sha256": hashlib.sha256(OVERLAY.read_bytes()).hexdigest(),
        "checks_passed": len(failures) == 0}, indent=2) + "\n")
    print()
    if failures:
        print(f"FAILED: {failures}")
        raise SystemExit(1)
    print("all V98 build self-checks passed")


if __name__ == "__main__":
    main()
