#!/usr/bin/env python3
"""Assemble and self-check the V98-R1 candidate: frozen V92 + windowed extra-cow buy.

Run from repo root:
    .venv/bin/python experiments/v98_economics/build_r1.py
"""

from __future__ import annotations

import base64
import hashlib
import importlib.util
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
V92 = ROOT / "experiments/v92_overflow_guard/candidate.py"
OVERLAY = HERE / "candidate_r1_overlay.py"
OUT = HERE / "candidate_r1.py"
failures: list[str] = []


def check(name, ok, detail=""):
    print(f"[{'PASS' if ok else 'FAIL'}] {name}{(' :: ' + detail) if detail else ''}")
    if not ok:
        failures.append(name)


def main():
    v92_text = V92.read_text()
    overlay_text = OVERLAY.read_text()
    b64 = base64.b64encode(v92_text.encode()).decode()
    literal = "\n".join(f'    "{b64[i:i + 76]}"' for i in range(0, len(b64), 76))
    OUT.write_text("# V98-R1 candidate: frozen V92 + windowed extra-cow buy.\n"
                   "# Generated by experiments/v98_economics/build_r1.py. Do not hand-edit.\n"
                   "import base64 as _r1_b64\n\n"
                   f"_V92_SOURCE_B64 = (\n{literal}\n)\n\n"
                   + v92_text + "\n\n" + overlay_text)
    digest = hashlib.sha256(OUT.read_bytes()).hexdigest()
    print(f"wrote {OUT}  sha256 {digest}\n")

    dec = base64.b64decode("".join(
        p.strip().strip('"')
        for p in OUT.read_text().split("_V92_SOURCE_B64 = (")[1].split(")")[0].splitlines()
    )).decode()
    check("embedded V92 byte-identical", dec == v92_text,
          hashlib.sha256(v92_text.encode()).hexdigest()[:16])

    spec = importlib.util.spec_from_file_location("v98r1", OUT)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    check("module loads with an entrypoint", callable(getattr(mod, "_kaggle_submission_entrypoint", None)))

    from kaggle_environments.agent import get_last_callable
    bound = get_last_callable(OUT.read_text(), None, str(OUT))
    check("loader binds the R1 entrypoint", getattr(bound, "__name__", "") == "_r1_entrypoint",
          getattr(bound, "__name__", ""))

    def obs(money=2000, free_pasture=True, shed=None):
        t = [[None] * 10 for _ in range(10)]
        t[3][3] = {"kind": "PLANT", "crop": "WHEAT", "planted_day": 0, "yield_units": 0,
                   "watered_today": True, "fertilized_until_day": -1}
        if free_pasture:
            t[2][2] = {"kind": "PASTURE"}
        s = {"COW": 0, "SHEEP": 0, "WHEAT": 10}
        s.update(shed or {})
        return {"day": 7, "hour": 6, "player": 0, "step": 174,
                "market": {"prices": {"COW": 400, "SHEEP": 500}},
                "private": {"shed": s, "seeds": {}, "inventories": [{}]},
                "farms": [{"money": money, "farmer": [4, 4], "hands": [],
                            "tiles": t, "unlocked_quadrants": ["NW"], "hires_today": 0}]}

    collecting = {"farmer": ["PICKUP", "SHEEP", 1], "hands": [],
                  "market": [["SELL", "WOOL", 2]]}
    idle = {"farmer": ["PASS"], "hands": [], "market": [["SELL", "WOOL", 2]]}

    mod._R1_DONE["bought"] = False
    a = mod._r1_apply(obs(), collecting)
    check("tape is collecting an animal -> BUY_ANIMAL COW appended",
          ["BUY_ANIMAL", "COW", 1] in a["market"], json.dumps(a["market"]))
    check("existing SELL preserved", ["SELL", "WOOL", 2] in a["market"])
    check("input not mutated", collecting["market"] == [["SELL", "WOOL", 2]])

    b = mod._r1_apply(obs(), collecting)
    check("LATCH: at most one extra cow is ever bought",
          "BUY_ANIMAL" not in json.dumps(b["market"]), json.dumps(b["market"]))

    mod._R1_DONE["bought"] = False
    a = mod._r1_apply(obs(), idle)
    check("REVISION: tape is NOT collecting -> no purchase (this is the R1 fix)",
          "BUY_ANIMAL" not in json.dumps(a["market"]), json.dumps(a["market"]))

    mod._R1_DONE["bought"] = False
    a = mod._r1_apply(obs(free_pasture=False), collecting)
    check("no free pasture -> no purchase", "BUY_ANIMAL" not in json.dumps(a["market"]))

    mod._R1_DONE["bought"] = False
    a = mod._r1_apply(obs(money=100), collecting)
    check("cash below the floor -> no purchase", "BUY_ANIMAL" not in json.dumps(a["market"]))

    mod._R1_DONE["bought"] = False
    a = mod._r1_apply(obs(shed={"COW": 1}), collecting)
    check("a cow already in the shed -> no purchase", "BUY_ANIMAL" not in json.dumps(a["market"]))

    mod._R1_DONE["bought"] = False
    a = mod._r1_apply(obs(shed={"WHEAT": 99}), collecting)
    check("shed too full -> no purchase", "BUY_ANIMAL" not in json.dumps(a["market"]))

    (HERE / "candidate_r1_build.json").write_text(json.dumps({
        "candidate": str(OUT), "sha256": digest,
        "v92_file_sha256": hashlib.sha256(V92.read_bytes()).hexdigest(),
        "overlay_sha256": hashlib.sha256(OVERLAY.read_bytes()).hexdigest(),
        "checks_passed": len(failures) == 0}, indent=2) + "\n")
    print()
    if failures:
        print(f"FAILED: {failures}")
        raise SystemExit(1)
    print("all V98-R1 build self-checks passed")


if __name__ == "__main__":
    main()
