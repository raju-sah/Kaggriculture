#!/usr/bin/env python3
"""Assemble and self-check a V96 candidate: frozen V92 source + one route overlay.

Generic over the overlay file so the same verified build path produces V96-A, V96-B and
any successor. The Kaggle submission receives exactly one file, so the frozen V92 source
is embedded verbatim; if it were imported by path the loader would raise on Kaggle, fall
into the all-PASS except branch and silently submit a do-nothing agent.

Run from repo root:
    .venv/bin/python experiments/v96_route/build.py --overlay candidate_a_overlay.py --name candidate_a
"""

from __future__ import annotations

import argparse
import base64
import hashlib
import importlib.util
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
V92 = ROOT / "experiments/v92_overflow_guard/candidate.py"

failures: list[str] = []


def check(name, ok, detail=""):
    print(f"[{'PASS' if ok else 'FAIL'}] {name}{(' :: ' + detail) if detail else ''}")
    if not ok:
        failures.append(name)


def build(overlay_path: Path, out_name: str) -> Path:
    v92_text = V92.read_text()
    overlay_text = overlay_path.read_text()
    # Split the overlay at its entrypoint so the entrypoint is emitted AFTER the
    # embedded V92. get_last_callable binds the last callable NAME in the exec env, and
    # the embedded V92 exec's its own V50 bundle mid-file, so ordering is load-bearing.
    candidates = [m for m in ("def _v96_entrypoint(", "def _v96b_entrypoint(",
                              "def _v96a_entrypoint(", "def _v96_entry(")
                 if m in overlay_text]
    if not candidates:
        raise SystemExit("overlay has no recognised entrypoint definition")
    marker = candidates[0]
    idx = overlay_text.index(marker)
    head = overlay_text[:idx]
    entry = overlay_text[idx:]
    b64 = base64.b64encode(v92_text.encode()).decode()
    literal = "\n".join(f'    "{b64[i:i + 76]}"' for i in range(0, len(b64), 76))
    pre = (
        f"# V96 candidate built from frozen V92 (embedded verbatim) + {overlay_path.name}.\n"
        "# Generated by experiments/v96_route/build.py. Do not hand-edit.\n"
        "import base64 as _v96_b64\n\n"
        f"_V92_SOURCE_B64 = (\n{literal}\n)\n\n"
    )
    out = HERE / out_name
    out.write_text(pre + v92_text + "\n\n" + head + entry)
    return out


def verify(out: Path, overlay_path: Path) -> dict:
    v92_text = V92.read_text()
    check("embedded V92 decodes byte-identical to the frozen V92 candidate",
          base64.b64decode("".join(
              part.strip().strip('"')
              for part in out.read_text().split("_V92_SOURCE_B64 = (")[1].split(")")[0].splitlines()
          )).decode() == v92_text,
          hashlib.sha256(v92_text.encode()).hexdigest()[:16])

    spec = importlib.util.spec_from_file_location("built_" + out.stem, out)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    check("module loads and exposes an entrypoint",
          callable(getattr(mod, "_kaggle_submission_entrypoint", None)))

    from kaggle_environments.agent import get_last_callable
    bound = get_last_callable(out.read_text(), None, str(out))
    check("Kaggle loader binds an entrypoint",
          getattr(bound, "__name__", "").endswith("entrypoint")
          or getattr(bound, "__name__", "") == "_kaggle_submission_entrypoint",
          getattr(bound, "__name__", ""))

    # Overlay must be a no-op outside its window and must not touch the market list.
    apply_fn = None
    for name in ("_v96b_apply", "_v96a_apply", "_v96_apply"):
        fn = getattr(mod, name, None)
        if callable(fn):
            apply_fn = fn
            break
    if apply_fn is None:
        raise SystemExit("built module exposes no overlay apply function")

    empty_farm = {"money": 5000, "farmer": [0, 0], "hands": [[1, 1]],
                  "tiles": [[None] * 10 for _ in range(10)]}
    obs = {"day": 30, "player": 0, "farms": [empty_farm],
           "private": {"shed": {}, "inventories": [{}, {}], "seeds": {}},
           "market": {"prices": {}}}
    act = {"farmer": ["PASS"], "hands": [["PASS"]], "market": [["SELL", "WOOL", 1]]}
    out_day30 = apply_fn(obs, act)
    check("no-op outside the overlay's day window",
          out_day30 == act, f"day=30 returned {out_day30}")

    act2 = {"farmer": ["PASS"], "hands": [["PASS"]], "market": [["SELL", "WOOL", 1]]}
    ins = {"day": 4, "player": 0, "farms": [empty_farm],
           "private": {"shed": {}, "inventories": [{}, {}], "seeds": {}},
           "market": {"prices": {}}}
    out_in = apply_fn(ins, act2)
    check("market list never modified", out_in.get("market") == [["SELL", "WOOL", 1]],
          json.dumps(out_in.get("market")))
    check("input action not mutated", act2["hands"] == [["PASS"]])

    return {
        "candidate": str(out),
        "sha256": hashlib.sha256(out.read_bytes()).hexdigest(),
        "overlay": str(overlay_path),
        "overlay_sha256": hashlib.sha256(overlay_path.read_bytes()).hexdigest(),
        "v92_source_sha256": hashlib.sha256(v92_text.encode()).hexdigest(),
        "v92_file_sha256": hashlib.sha256(V92.read_bytes()).hexdigest(),
        "checks_passed": len(failures) == 0,
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--overlay", required=True)
    ap.add_argument("--name", required=True)
    args = ap.parse_args()
    overlay = HERE / args.overlay
    out = build(overlay, args.name + ".py")
    print(f"wrote {out}  sha256 {hashlib.sha256(out.read_bytes()).hexdigest()}\n")
    meta = verify(out, overlay)
    (HERE / f"{args.name}_build.json").write_text(json.dumps(meta, indent=2) + "\n")
    print()
    if failures:
        print(f"FAILED: {failures}")
        raise SystemExit(1)
    print("all build self-checks passed")


if __name__ == "__main__":
    main()
