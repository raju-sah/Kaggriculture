#!/usr/bin/env python3
"""Assemble and self-check a V97 candidate: frozen V92 source + the multi-turn route.

The Kaggle submission receives one file, so the frozen V92 source is embedded verbatim.
The route overlay is prepended and its entrypoint re-emitted AFTER the embedded V92, so
the loader's get_last_callable binds the route entrypoint (it binds the last callable
NAME in the exec environment, and the embedded V92 exec's its own V50 bundle mid-file,
so ordering is load-bearing).

Run from repo root:
    .venv/bin/python experiments/v97_route/build.py
"""

from __future__ import annotations

import base64
import hashlib
import importlib.util
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
V92 = ROOT / "experiments/v92_overflow_guard/candidate.py"
OVERLAY = HERE / "route_overlay.py"
OUT = HERE / "candidate.py"

failures: list[str] = []


def check(name, ok, detail=""):
    print(f"[{'PASS' if ok else 'FAIL'}] {name}{(' :: ' + detail) if detail else ''}")
    if not ok:
        failures.append(name)


def main():
    v92_text = V92.read_text()
    overlay_text = OVERLAY.read_text()
    marker = "def _v97_entrypoint(obs, configuration=None):"
    idx = overlay_text.index(marker)
    head = overlay_text[:idx]
    entry = overlay_text[idx:]

    b64 = base64.b64encode(v92_text.encode()).decode()
    literal = "\n".join(f'    "{b64[i:i + 76]}"' for i in range(0, len(b64), 76))
    pre = (
        "# V97 candidate: frozen V92 (embedded verbatim) + bounded multi-turn worker route.\n"
        "# Generated by experiments/v97_route/build.py. Do not hand-edit.\n"
        "import base64 as _v97_b64\n\n"
        f"_V92_SOURCE_B64 = (\n{literal}\n)\n\n"
    )
    OUT.write_text(pre + v92_text + "\n\n" + head + entry)
    digest = hashlib.sha256(OUT.read_bytes()).hexdigest()
    print(f"wrote {OUT}  sha256 {digest}\n")

    # ---- self-checks -------------------------------------------------------
    dec = base64.b64decode("".join(
        part.strip().strip('"')
        for part in OUT.read_text().split("_V92_SOURCE_B64 = (")[1].split(")")[0].splitlines()
    )).decode()
    check("embedded V92 decodes byte-identical to the frozen V92 candidate",
          dec == v92_text, hashlib.sha256(v92_text.encode()).hexdigest()[:16])

    spec = importlib.util.spec_from_file_location("v97_built", OUT)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    check("module loads and exposes _kaggle_submission_entrypoint",
          callable(getattr(mod, "_kaggle_submission_entrypoint", None)))

    from kaggle_environments.agent import get_last_callable
    bound = get_last_callable(OUT.read_text(), None, str(OUT))
    check("Kaggle loader binds the route entrypoint",
          getattr(bound, "__name__", "") == "_v97_entrypoint",
          getattr(bound, "__name__", ""))

    # The route must never touch the market list.
    def mkobs(day, hands, farmer_pos, hand_pos, tiles, shed=None, invs=None):
        farm = {"money": 9000, "farmer": list(farmer_pos), "hands": [list(p) for p in hand_pos],
                "tiles": [row[:] for row in tiles], "unlocked_quadrants": ["NW"]}
        return {
            "day": day, "hour": 5, "player": 0, "step": day * 24 + 5,
            "market": {"prices": {"STRAWBERRY": 140, "WHEAT": 40}},
            "private": {"shed": dict(shed or {}), "seeds": {},
                        "inventories": [dict(i) for i in (invs or [{}] + [{} for _ in hands])]},
            "farms": [farm],
        }

    def mktact(hands):
        return {"farmer": ["PASS"], "hands": [list(h) for h in hands],
                "market": [["SELL", "STRAWBERRY", 2]]}

    blank = [[None] * 10 for _ in range(10)]
    # outside the window
    obs = mkobs(30, [["PASS"]], (0, 0), [(2, 2)], blank)
    a = mod._v97_apply(obs, mktact([["PASS"]]))
    check("no-op outside days 12-23", a["hands"] == [["PASS"]] and a["market"] == [["SELL", "STRAWBERRY", 2]])

    # in-window, hand standing on a ripe strawberry, free of duties -> harvest.
    # STRAWBERRY first_yield_day is 10, so planted_day must be <= day-10.
    tiles = [row[:] for row in blank]
    tiles[2][2] = {"kind": "PLANT", "crop": "STRAWBERRY", "planted_day": 4, "yield_units": 2,
                   "watered_today": True, "fertilized_until_day": -1}
    obs = mkobs(15, [["PASS"]], (0, 0), [(2, 2)], tiles)
    a = mod._v97_apply(obs, mktact([["PASS"]]))
    check("adjacent to ripe target -> HARVEST", a["hands"] == [["HARVEST"]], json.dumps(a["hands"]))
    check("market list never modified by the route", a["market"] == [["SELL", "STRAWBERRY", 2]])

    # in-window, hand two tiles west of the target -> a single EAST step toward it
    # (this is the multi-turn evidence: the route emits MOVE, not just work)
    obs = mkobs(15, [["PASS"]], (0, 0), [(0, 2)], tiles)
    a = mod._v97_apply(obs, mktact([["PASS"]]))
    check("two tiles away -> a single MOVE toward the target",
          a["hands"] == [["EAST"]], json.dumps(a["hands"]))

    # duty protection: a hand on FEED is never displaced
    obs = mkobs(15, [["FEED"]], (0, 0), [(2, 2)], tiles)
    a = mod._v97_apply(obs, mktact([["FEED"]]))
    check("FEED hand never displaced", a["hands"] == [["FEED"]], json.dumps(a["hands"]))

    # delivery: a carrying hand standing on a real engine shed-access tile -> DROP.
    # The engine's _shed_access_tiles(10) is the INNER corner {(4,4),(4,5),(5,4),(5,5)}.
    check("drop tiles match engine._shed_access_tiles",
          sorted(mod._v97_drop_tiles(10)) == sorted([(4, 4), (4, 5), (5, 4), (5, 5)]),
          str(sorted(mod._v97_drop_tiles(10))))
    invs = [{}, {"STRAWBERRY": 2}]
    obs = mkobs(15, [["PASS"]], (0, 0), [(4, 4)], tiles, shed={}, invs=invs)
    a = mod._v97_apply(obs, mktact([["PASS"]]))
    check("carrying hand on a real shed-access tile -> DROP", a["hands"] == [["DROP"]], json.dumps(a["hands"]))

    # REGRESSION: the earlier version used OUTER-corner tiles, so 18 of 84 DROPs were
    # silent no-ops and the load was deleted. A hand on the outer corner must now WALK
    # to a real shed tile rather than issuing a no-op DROP.
    invs2 = [{}, {"STRAWBERRY": 2}]
    obs = mkobs(15, [["PASS"]], (0, 0), [(0, 0)], tiles, shed={}, invs=invs2)
    a = mod._v97_apply(obs, mktact([["PASS"]]))
    check("REGRESSION: outer-corner carrying hand walks to a real shed tile, no silent DROP",
          a["hands"] != [["DROP"]] and a["hands"][0][0] in ("EAST", "SOUTH", "NORTH", "WEST"),
          json.dumps(a["hands"]))

    meta = {
        "candidate": str(OUT),
        "sha256": digest,
        "v92_source_sha256": hashlib.sha256(v92_text.encode()).hexdigest(),
        "v92_file_sha256": hashlib.sha256(V92.read_bytes()).hexdigest(),
        "route_overlay_sha256": hashlib.sha256(OVERLAY.read_bytes()).hexdigest(),
        "checks_passed": len(failures) == 0,
    }
    (HERE / "candidate_build.json").write_text(json.dumps(meta, indent=2) + "\n")
    print()
    if failures:
        print(f"FAILED: {failures}")
        raise SystemExit(1)
    print("all build self-checks passed")


if __name__ == "__main__":
    main()
