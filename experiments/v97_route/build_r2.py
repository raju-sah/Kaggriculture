#!/usr/bin/env python3
"""Assemble and self-check the V97-R2 candidate: frozen V92 + single-errand local-gate route.

Run from repo root:
    .venv/bin/python experiments/v97_route/build_r2.py
"""

from __future__ import annotations

import base64
import hashlib
import importlib.util
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
V92 = ROOT / "experiments/v92_overflow_guard/candidate.py"
OVERLAY = HERE / "route_r2_overlay.py"
OUT = HERE / "candidate_r2.py"
failures: list[str] = []


def check(name, ok, detail=""):
    print(f"[{'PASS' if ok else 'FAIL'}] {name}{(' :: ' + detail) if detail else ''}")
    if not ok:
        failures.append(name)


def main():
    v92_text = V92.read_text()
    overlay_text = OVERLAY.read_text()
    marker = "def _r2_entrypoint(obs, configuration=None):"
    idx = overlay_text.index(marker)
    head, entry = overlay_text[:idx], overlay_text[idx:]
    b64 = base64.b64encode(v92_text.encode()).decode()
    literal = "\n".join(f'    "{b64[i:i + 76]}"' for i in range(0, len(b64), 76))
    pre = ("# V97-R2 candidate: frozen V92 (embedded verbatim) + single-errand local-gate route.\n"
           "# Generated by experiments/v97_route/build_r2.py. Do not hand-edit.\n"
           "import base64 as _r2_b64\n\n"
           f"_V92_SOURCE_B64 = (\n{literal}\n)\n\n")
    OUT.write_text(pre + v92_text + "\n\n" + head + entry)
    digest = hashlib.sha256(OUT.read_bytes()).hexdigest()
    print(f"wrote {OUT}  sha256 {digest}\n")

    dec = base64.b64decode("".join(
        p.strip().strip('"')
        for p in OUT.read_text().split("_V92_SOURCE_B64 = (")[1].split(")")[0].splitlines()
    )).decode()
    check("embedded V92 decodes byte-identical", dec == v92_text,
          hashlib.sha256(v92_text.encode()).hexdigest()[:16])

    spec = importlib.util.spec_from_file_location("r2_built", OUT)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    check("module loads and exposes an entrypoint",
          callable(getattr(mod, "_kaggle_submission_entrypoint", None)))

    from kaggle_environments.agent import get_last_callable
    bound = get_last_callable(OUT.read_text(), None, str(OUT))
    check("Kaggle loader binds the R2 entrypoint",
          getattr(bound, "__name__", "") == "_r2_entrypoint", getattr(bound, "__name__", ""))

    check("drop tiles match engine._shed_access_tiles",
          sorted(mod._r2_drop_tiles(10)) == sorted([(4, 4), (4, 5), (5, 4), (5, 5)]),
          str(sorted(mod._r2_drop_tiles(10))))

    def mkobs(day, hands, farmer_pos, hand_pos, tiles, shed=None, invs=None):
        farm = {"money": 9000, "farmer": list(farmer_pos), "hands": [list(p) for p in hand_pos],
                "tiles": [row[:] for row in tiles], "unlocked_quadrants": ["NW"]}
        return {"day": day, "hour": 5, "player": 0, "step": day * 24 + 5,
                "market": {"prices": {"STRAWBERRY": 140, "WHEAT": 40}},
                "private": {"shed": dict(shed or {}), "seeds": {},
                            "inventories": [dict(i) for i in (invs or [{}] + [{} for _ in hands])]},
                "farms": [farm]}

    def mktact(h):
        return {"farmer": ["PASS"], "hands": [list(x) for x in h], "market": [["SELL", "STRAWBERRY", 2]]}

    blank = [[None] * 10 for _ in range(10)]
    # A 4-unit ripe strawberry worth 4 x 142.65 = 570.60, above the 400 threshold.
    ripe = [row[:] for row in blank]
    ripe[2][2] = {"kind": "PLANT", "crop": "STRAWBERRY", "planted_day": 2, "yield_units": 4,
                  "watered_today": True, "fertilized_until_day": -1}

    mod._R2_TAKEN["used"] = False
    obs = mkobs(15, [["PASS"]], (0, 0), [(1, 2)], ripe)   # adjacent (distance 1) clean tile
    a = mod._r2_apply(obs, mktact([["PASS"]]))
    check("clean tile + nearby ripe target -> errand starts (a MOVE, the multi-turn step)",
          a["hands"] == [["EAST"]], json.dumps(a["hands"]))
    check("market list untouched", a["market"] == [["SELL", "STRAWBERRY", 2]])
    b = mod._r2_apply(obs, mktact([["PASS"]]))
    check("LATCH: the route acts at most once per process", b["hands"] == [["PASS"]],
          json.dumps(b["hands"]))

    # LOCAL gate: a hand standing on an UNWATERED plant is not borrowable even though
    # the rest of the board is fine. This is the R1 -> R2 difference.
    # NOTE tiles are [y][x] and hand positions are [x, y]; a hand at [2,1] is on
    # tiles[1][2]. Keeping that consistent here so the fixture is unambiguous.
    mod._R2_TAKEN["used"] = False
    dirty = [row[:] for row in blank]
    dirty[1][2] = {"kind": "PLANT", "crop": "WHEAT", "planted_day": 10, "yield_units": 0,
                   "watered_today": False, "fertilized_until_day": -1}
    dirty[2][2] = ripe[2][2]
    obs_d = mkobs(15, [["PASS"]], (0, 0), [(2, 1)], dirty)
    a = mod._r2_apply(obs_d, mktact([["PASS"]]))
    check("LOCAL GATE: hand on an unwatered plant is not borrowed (R2 vs R1)",
          a["hands"] == [["PASS"]], json.dumps(a["hands"]))

    # LOCAL gate: a hand standing on a RIPE plant is not borrowed.
    mod._R2_TAKEN["used"] = False
    on_ripe = [row[:] for row in blank]
    on_ripe[1][2] = {"kind": "PLANT", "crop": "STRAWBERRY", "planted_day": 2, "yield_units": 3,
                     "watered_today": True, "fertilized_until_day": -1}
    on_ripe[2][2] = ripe[2][2]
    obs_r = mkobs(15, [["PASS"]], (0, 0), [(2, 1)], on_ripe)
    a = mod._r2_apply(obs_r, mktact([["PASS"]]))
    check("LOCAL GATE: hand on a ripe plant is not borrowed",
          a["hands"] == [["PASS"]], json.dumps(a["hands"]))

    # REACH: far target ignored.
    mod._R2_TAKEN["used"] = False
    far = [row[:] for row in blank]
    far[8][8] = {"kind": "PLANT", "crop": "STRAWBERRY", "planted_day": 2, "yield_units": 4,
                 "watered_today": True, "fertilized_until_day": -1}
    a = mod._r2_apply(mkobs(15, [["PASS"]], (0, 0), [(0, 0)], far), mktact([["PASS"]]))
    check(f"REACH: a target beyond reach {mod._R2_REACH} is ignored", a["hands"] == [["PASS"]],
          json.dumps(a["hands"]))

    # Low-value target ignored (WHEAT at 40.83 x 4 = 163 < 400 threshold).
    mod._R2_TAKEN["used"] = False
    cheap = [row[:] for row in blank]
    cheap[2][2] = {"kind": "PLANT", "crop": "WHEAT", "planted_day": 0, "yield_units": 6,
                   "watered_today": True, "fertilized_until_day": -1}
    a = mod._r2_apply(mkobs(15, [["PASS"]], (0, 0), [(1, 2)], cheap), mktact([["PASS"]]))
    check("VALUE: a low-value target below the opportunity-cost threshold is ignored",
          a["hands"] == [["PASS"]], json.dumps(a["hands"]))

    # Delivery on a real shed tile.
    mod._R2_TAKEN["used"] = False
    a = mod._r2_apply(mkobs(15, [["PASS"]], (0, 0), [(4, 4)], ripe, invs=[{}, {"STRAWBERRY": 3}]),
                      mktact([["PASS"]]))
    check("delivery: carrying hand on a real shed-access tile -> DROP", a["hands"] == [["DROP"]],
          json.dumps(a["hands"]))

    # No-op outside the window.
    mod._R2_TAKEN["used"] = False
    a = mod._r2_apply(mkobs(25, [["PASS"]], (0, 0), [(0, 1)], ripe), mktact([["PASS"]]))
    check("no-op outside days 12-20", a["hands"] == [["PASS"]])

    (HERE / "candidate_r2_build.json").write_text(json.dumps({
        "candidate": str(OUT), "sha256": digest,
        "v92_file_sha256": hashlib.sha256(V92.read_bytes()).hexdigest(),
        "overlay_sha256": hashlib.sha256(OVERLAY.read_bytes()).hexdigest(),
        "checks_passed": len(failures) == 0}, indent=2) + "\n")
    print()
    if failures:
        print(f"FAILED: {failures}")
        raise SystemExit(1)
    print("all R2 build self-checks passed")


if __name__ == "__main__":
    main()
