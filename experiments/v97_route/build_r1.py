#!/usr/bin/env python3
"""Assemble and self-check a V97 candidate from a given route overlay.

Generic so the same verified build path produces the original route and the R1 revision.
The frozen V92 source is embedded verbatim; the overlay is prepended and its entrypoint
re-emitted AFTER the embedded V92, because the Kaggle loader's get_last_callable binds
the last callable NAME in the exec environment and the embedded V92 exec's its own V50
bundle mid-file, so ordering is load-bearing.

Run from repo root:
    .venv/bin/python experiments/v97_route/build_r1.py
"""

from __future__ import annotations

import base64
import hashlib
import importlib.util
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
V92 = ROOT / "experiments/v92_overflow_guard/candidate.py"
OVERLAY = HERE / "route_r1_overlay.py"
OUT = HERE / "candidate_r1.py"

failures: list[str] = []


def check(name, ok, detail=""):
    print(f"[{'PASS' if ok else 'FAIL'}] {name}{(' :: ' + detail) if detail else ''}")
    if not ok:
        failures.append(name)


def main():
    v92_text = V92.read_text()
    overlay_text = OVERLAY.read_text()
    marker = "def _r1_entrypoint(obs, configuration=None):"
    idx = overlay_text.index(marker)
    head = overlay_text[:idx]
    entry = overlay_text[idx:]

    b64 = base64.b64encode(v92_text.encode()).decode()
    literal = "\n".join(f'    "{b64[i:i + 76]}"' for i in range(0, len(b64), 76))
    pre = (
        "# V97-R1 candidate: frozen V92 (embedded verbatim) + single-errand bounded route.\n"
        "# Generated by experiments/v97_route/build_r1.py. Do not hand-edit.\n"
        "import base64 as _r1_b64\n\n"
        f"_V92_SOURCE_B64 = (\n{literal}\n)\n\n"
    )
    OUT.write_text(pre + v92_text + "\n\n" + head + entry)
    digest = hashlib.sha256(OUT.read_bytes()).hexdigest()
    print(f"wrote {OUT}  sha256 {digest}\n")

    dec = base64.b64decode("".join(
        p.strip().strip('"')
        for p in OUT.read_text().split("_V92_SOURCE_B64 = (")[1].split(")")[0].splitlines()
    )).decode()
    check("embedded V92 decodes byte-identical to the frozen V92 candidate",
          dec == v92_text, hashlib.sha256(v92_text.encode()).hexdigest()[:16])

    spec = importlib.util.spec_from_file_location("r1_built", OUT)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    check("module loads and exposes _kaggle_submission_entrypoint",
          callable(getattr(mod, "_kaggle_submission_entrypoint", None)))

    from kaggle_environments.agent import get_last_callable
    bound = get_last_callable(OUT.read_text(), None, str(OUT))
    check("Kaggle loader binds the R1 route entrypoint",
          getattr(bound, "__name__", "") == "_r1_entrypoint", getattr(bound, "__name__", ""))

    check("drop tiles match engine._shed_access_tiles",
          sorted(mod._r1_drop_tiles(10)) == sorted([(4, 4), (4, 5), (5, 4), (5, 5)]),
          str(sorted(mod._r1_drop_tiles(10))))

    def mkobs(day, hands, farmer_pos, hand_pos, tiles, shed=None, invs=None, fed=True, watered=True):
        farm = {"money": 9000, "farmer": list(farmer_pos), "hands": [list(p) for p in hand_pos],
                "tiles": [row[:] for row in tiles], "unlocked_quadrants": ["NW"]}
        return {"day": day, "hour": 5, "player": 0, "step": day * 24 + 5,
                "market": {"prices": {"STRAWBERRY": 140, "WHEAT": 40}},
                "private": {"shed": dict(shed or {}), "seeds": {},
                            "inventories": [dict(i) for i in (invs or [{}] + [{} for _ in hands])]},
                "farms": [farm]}

    def mktact(hands):
        return {"farmer": ["PASS"], "hands": [list(h) for h in hands],
                "market": [["SELL", "STRAWBERRY", 2]]}

    blank = [[None] * 10 for _ in range(10)]
    tiles = [row[:] for row in blank]
    tiles[2][2] = {"kind": "PLANT", "crop": "STRAWBERRY", "planted_day": 2, "yield_units": 4,
                   "watered_today": True, "fertilized_until_day": -1}

    # LATCH: the route must fire at most once per process.
    mod._R1_TAKEN["used"] = False
    obs = mkobs(15, [["PASS"]], (0, 0), [(2, 2)], tiles)
    a1 = mod._r1_apply(obs, mktact([["PASS"]]))
    check("ripe, watered, fed board -> HARVEST (errand starts)",
          a1["hands"] == [["HARVEST"]], json.dumps(a1["hands"]))
    a2 = mod._r1_apply(obs, mktact([["PASS"]]))
    check("LATCH: route never acts a second time", a2["hands"] == [["PASS"]], json.dumps(a2["hands"]))

    mod._R1_TAKEN["used"] = False
    a3 = mod._r1_apply(obs, mktact([["PASS"]]))
    check("market list untouched", a3["market"] == [["SELL", "STRAWBERRY", 2]])

    # DUTY GATE: an unwatered plant anywhere blocks the route.
    mod._R1_TAKEN["used"] = False
    dry = [row[:] for row in tiles]
    dry[6][6] = {"kind": "PLANT", "crop": "WHEAT", "planted_day": 10, "yield_units": 0,
                 "watered_today": False, "fertilized_until_day": -1}
    obs_dry = mkobs(15, [["PASS"]], (0, 0), [(2, 2)], dry)
    a4 = mod._r1_apply(obs_dry, mktact([["PASS"]]))
    check("DUTY GATE: an unwatered plant on the board blocks the errand",
          a4["hands"] == [["PASS"]], json.dumps(a4["hands"]))

    # DUTY GATE: an unfed animal blocks it too.
    mod._R1_TAKEN["used"] = False
    hungry = [row[:] for row in tiles]
    hungry[7][7] = {"kind": "PASTURE", "animal": "COW", "fed_today": False, "yield_units": 0}
    obs_hungry = mkobs(15, [["PASS"]], (0, 0), [(2, 2)], hungry)
    a5 = mod._r1_apply(obs_hungry, mktact([["PASS"]]))
    check("DUTY GATE: an unfed animal on the board blocks the errand",
          a5["hands"] == [["PASS"]], json.dumps(a5["hands"]))

    # REACH: a target beyond _R1_REACH is ignored.
    mod._R1_TAKEN["used"] = False
    far = [row[:] for row in blank]
    far[8][8] = {"kind": "PLANT", "crop": "STRAWBERRY", "planted_day": 2, "yield_units": 4,
                 "watered_today": True, "fertilized_until_day": -1}
    obs_far = mkobs(15, [["PASS"]], (0, 0), [(0, 0)], far)
    a6 = mod._r1_apply(obs_far, mktact([["PASS"]]))
    check(f"REACH: a target {mod._R1_REACH} tiles away is ignored (no long walk)",
          a6["hands"] == [["PASS"]], f"reach={mod._R1_REACH} dist=16 {json.dumps(a6['hands'])}")

    # DELIVERY: a carrying hand on a real shed tile drops.
    mod._R1_TAKEN["used"] = False
    invs = [{}, {"STRAWBERRY": 3}]
    obs_carry = mkobs(15, [["PASS"]], (0, 0), [(4, 4)], tiles, shed={}, invs=invs)
    a7 = mod._r1_apply(obs_carry, mktact([["PASS"]]))
    check("delivery: carrying hand on a real shed-access tile -> DROP",
          a7["hands"] == [["DROP"]], json.dumps(a7["hands"]))

    (HERE / "candidate_r1_build.json").write_text(json.dumps({
        "candidate": str(OUT), "sha256": digest,
        "v92_file_sha256": hashlib.sha256(V92.read_bytes()).hexdigest(),
        "overlay_sha256": hashlib.sha256(OVERLAY.read_bytes()).hexdigest(),
        "checks_passed": len(failures) == 0,
    }, indent=2) + "\n")
    print()
    if failures:
        print(f"FAILED: {failures}")
        raise SystemExit(1)
    print("all R1 build self-checks passed")


if __name__ == "__main__":
    main()
