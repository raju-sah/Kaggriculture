def _v92_shed_total(private):
    return sum((private.get("shed") or {}).values())


def _v92_carried_total(private):
    return sum(
        sum((inv or {}).values())
        for inv in (private.get("inventories") or [])
    )


def _v92_live_animals(farm):
    return sum(
        1
        for row in farm.get("tiles") or []
        for tile in row
        if isinstance(tile, dict) and tile.get("animal")
    )


def _v92_buy_units(orders, item):
    return sum(int(o[2]) for o in orders if len(o) > 2 and o[0] == "BUY_PRODUCT" and o[1] == item)


def _v92_apply(obs, action):
    day = int(obs.get("day", 0) or 0)
    hour = int(obs.get("hour", 0) or 0)
    if day != GUARD_DAY or hour != GUARD_HOUR:
        return action

    seat = int(obs.get("player", 0) or 0)
    farms = obs.get("farms") or []
    if seat >= len(farms):
        return action
    farm = farms[seat]
    private = obs.get("private") or {}

    orders = list(action.get("market") or [])
    wheat_buys = _v92_buy_units(orders, "WHEAT")
    fert_buys = _v92_buy_units(orders, "FERTILIZER")
    if wheat_buys <= 0 and fert_buys <= 0:
        return action

    shed_now = _v92_shed_total(private)
    carried_now = _v92_carried_total(private)
    projected = shed_now + carried_now + wheat_buys + fert_buys + HARVEST_ALLOWANCE
    if projected <= SHED_CAPACITY:
        return action

    # Reserve floor, expressed as units that must REMAIN BOUGHT rather than units
    # left unpurchased. An earlier version of this guard used a per-animal wheat
    # floor, which on the audited state (16 animals, a 16-unit wheat buy) forbade
    # trimming wheat at all and left the overflow uncorrectable. The binding
    # reserve is what the farm still holds in the shed: shed wheat and shed
    # fertilizer are what feed the next day, not this turn's order quantity.
    shed = private.get("shed") or {}
    shed_wheat = int(shed.get("WHEAT", 0) or 0)
    shed_fert = int(shed.get("FERTILIZER", 0) or 0)
    # Keep buying at least the smaller of what was ordered and a small floor, so
    # the farm never abandons feed/soil entirely, and keep existing shed stock.
    wheat_keep = min(wheat_buys, max(0, min(shed_wheat, wheat_buys)))
    fert_keep = min(fert_buys, MIN_FERT_RESERVE)

    new_wheat = wheat_buys
    new_fert = min(fert_buys, MAX_FERT_BUY)
    if new_fert < fert_keep:
        new_fert = fert_keep

    # Recompute projection with the adjusted buys and trim in bulk, not one unit
    # per pass: a one-unit-per-pass loop cannot cover a double-digit excess.
    def projected(wheat_qty, fert_qty):
        return shed_now + carried_now + wheat_qty + fert_qty + HARVEST_ALLOWANCE

    guard_passes = 0
    while projected(new_wheat, new_fert) > SHED_CAPACITY and guard_passes < 32:
        guard_passes += 1
        # Trim fertilizer first (cheapest per unit), then wheat, but never below
        # the floors.
        if new_fert > fert_keep:
            new_fert -= 1
        elif new_wheat > wheat_keep:
            new_wheat -= 1
        else:
            break

    if new_wheat == wheat_buys and new_fert == fert_buys:
        return action

    new_orders = []
    for order in orders:
        if len(order) > 2 and order[0] == "BUY_PRODUCT" and order[1] == "FERTILIZER":
            if new_fert > 0:
                new_orders.append(["BUY_PRODUCT", "FERTILIZER", new_fert])
        elif len(order) > 2 and order[0] == "BUY_PRODUCT" and order[1] == "WHEAT":
            if new_wheat > 0:
                new_orders.append(["BUY_PRODUCT", "WHEAT", new_wheat])
        else:
            new_orders.append(list(order))

    action = _v92_copy.deepcopy(action)
    action["market"] = new_orders
    return action


def _v92_entrypoint(obs, configuration=None):
    return _v92_apply(obs, _v50_agent(obs, configuration))


# ---------------------------------------------------------------------------
# V93 overlay: adaptive WOOL quote-floor hold.
#
# The mechanism, and why this is forecast-free
# -------------------------------------------
# reward is final money only (engine line 961), so a unit that is not converted
# to cash is worth $0 regardless of what it is. The realization ledger over the
# 14 official replays shows the farm produces WOOL at scale and realizes it at
# roughly a tenth of its own peak quote: episode 114166061 sold 282 WOOL at an
# average of $21.8 against a peak quote of $218. That collapse is arithmetic,
# not bad luck. MARKET_I0 is 10000, the market starts at exactly I0, and WOOL
# uses above_func "sq" with above_target 3.20, so price falls as
# 200 - 0.05805*d^2 where d = inventory - 10000 and hits the $1 floor at d ~ 58.
# WOOL is the most saturating product in the game. WHEAT and EGG use "log" and
# never saturate at this scale, which is exactly why they realize at ~100% of
# their peak quote and WOOL does not.
#
# Engine line 659 is what makes the hold profitable rather than merely cautious:
# a SELL at or below the $1 floor does not add supply to the market. A floored
# sale is a pure $1 liquidation that also fails to depress the opponent, and it
# permanently converts a unit that could have been worth $200 into $1. The only
# exogenous demand in the game is _town_consume, which is what makes any
# recovery possible at all, and the cohort shows the quote genuinely recovering
# inside the game ($18 and $31 by day 22 in 114166061, $55 by day 22 in
# 114167570). Withholding supply lets that demand clear the glut, so a later
# sale of the same unit receives a strictly higher price.
#
# The rule is triggered by the CURRENTLY OBSERVED quote, which is a field of the
# observation. It is not a prediction of when the price will recover, so it needs
# no forecast and no timing model.
#
# What it does not do
# -------------------
# It does not touch production. Harvest, feed and care are untouched and the
# herd is identical. It does not suppress a SELL that the frozen route already
# placed; it only WITHHOLDS the WOOL quantity the route is adding on a floored
# turn, and restores that route's own WOOL order on any later turn whose quote
# is above the floor. It does not add, remove or reorder any non-WOOL order and
# it never touches a unit action.
#
# It is a no-op when the WOOL quote is healthy. In a game where WOOL holds a
# good quote throughout, the rule never fires and V93 submits byte-identical
# actions to V92. That is the property that makes this a profit argument rather
# than a win/loss argument: the WOOL collapse is not loss-specific, winners
# 114158802, 114164630 and 114170594 all show the same $1-$5 day-15-to-17 sales.
# ---------------------------------------------------------------------------

WOOL = "WOOL"
PRICE_FLOOR = 1          # engine PRICE_FLOOR; a sale at or below this adds no supply


def _v93_wool_quote(obs):
    """The currently observed WOOL quote, or None if the observation omits it."""
    prices = (obs.get("market") or {}).get("prices") or {}
    quote = prices.get(WOOL)
    if quote is None:
        return None
    try:
        return float(quote)
    except (TypeError, ValueError):
        return None


def _v93_apply(obs, action):
    """Hold new WOOL sell volume while the observed quote sits at the price floor."""
    quote = _v93_wool_quote(obs)
    if quote is None or quote > PRICE_FLOOR:
        # Healthy quote, or no quote to act on. Leave the frozen route untouched.
        return action

    orders = list(action.get("market") or [])
    wool_sells = [o for o in orders if len(o) > 2 and o[0] == "SELL" and o[1] == WOOL]
    if not wool_sells:
        # Nothing new is being offered, so there is nothing to withhold. Note
        # that this does not touch any shed stock the route chose not to sell.
        return action

    new_orders = []
    for order in orders:
        if len(order) > 2 and order[0] == "SELL" and order[1] == WOOL:
            continue  # withhold this turn's new WOOL volume; sell it above the floor
        new_orders.append(list(order))

    action = _v92_copy.deepcopy(action)
    action["market"] = new_orders
    return action


def _v93_entrypoint(obs, configuration=None):
    return _v93_apply(obs, _v92_entrypoint(obs, configuration))


def _kaggle_submission_entrypoint(obs, configuration=None):
    return _v93_entrypoint(obs, configuration)
