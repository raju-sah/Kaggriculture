#!/usr/bin/env python3
"""Assemble and self-check the V95 candidate: frozen V92 source + the fert overlay.

The Kaggle submission receives exactly one file, so the V95 candidate must embed the
frozen V92 source verbatim rather than importing it from a path. If it imported by
path, the loader on Kaggle would raise, fall into the all-PASS except branch, and
silently submit a do-nothing agent -- the exact failure V92's verify_embedded_source.py
was written to catch. This builder therefore embeds the real bytes and then proves it.

Run from repo root:
    .venv/bin/python experiments/v95_loss_driven/build_candidate.py
"""

from __future__ import annotations

import base64
import hashlib
import importlib.util
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
V92 = ROOT / "experiments/v92_overflow_guard/candidate.py"
OVERLAY = HERE / "candidate_overlay.py"
OUT = HERE / "candidate.py"

failures: list[str] = []


def check(name, ok, detail=""):
    print(f"[{'PASS' if ok else 'FAIL'}] {name}{(' :: ' + detail) if detail else ''}")
    if not ok:
        failures.append(name)


def main():
    v92_text = V92.read_text()
    overlay_text = OVERLAY.read_text()

    # The overlay's tail (from _v95_entrypoint onward) is re-emitted AFTER the
    # embedded V92 so that _kaggle_submission_entrypoint is the last module-level
    # callable in the file. The Kaggle loader's get_last_callable returns the LAST
    # definition, so ordering here is load-bearing, not cosmetic.
    marker = "def _v95_entrypoint(obs, configuration=None):"
    idx = overlay_text.index(marker)
    head = overlay_text[:idx]
    # kaggle_environments.agent.get_last_callable returns the last CALLABLE VALUE in
    # the exec environment dict, i.e. the last name in ASSIGNMENT order -- not the
    # last function in source order. The embedded V92 exec's its own V50 bundle
    # mid-file, which registers further callables afterwards. So the entrypoint is
    # bound as a plain assignment at the very end, making it the final name bound.
    entry = """
def _v95_entrypoint(obs, configuration=None):
    return _v95_apply(obs, _v92_entrypoint(obs, configuration))


_kaggle_submission_entrypoint = _v95_entrypoint
"""
    b64 = base64.b64encode(v92_text.encode()).decode()
    chunks = [b64[i:i + 76] for i in range(0, len(b64), 76)]
    literal = "\n".join(f'    "{c}"' for c in chunks)
    pre = (
        "# V95 candidate: frozen V92 (embedded verbatim) + adaptive fertilizer-apply overlay.\n"
        "# Generated by experiments/v95_loss_driven/build_candidate.py. Do not hand-edit.\n"
        "import base64 as _v95_b64\n\n"
        f"_V92_SOURCE_B64 = (\n{literal}\n)\n\n"
    )
    assembled = pre + v92_text + "\n\n" + head + entry
    OUT.write_text(assembled)
    digest = hashlib.sha256(OUT.read_bytes()).hexdigest()
    print(f"wrote {OUT}  sha256 {digest}\n")

    # --- self-checks -------------------------------------------------------
    check("embedded V92 decodes byte-identical to experiments/v92_overflow_guard/candidate.py",
          base64.b64decode(b64).decode() == v92_text,
          hashlib.sha256(v92_text.encode()).hexdigest()[:16])

    spec = importlib.util.spec_from_file_location("v95_built", OUT)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    check("module loads and defines _kaggle_submission_entrypoint",
          callable(getattr(mod, "_kaggle_submission_entrypoint", None)))

    from kaggle_environments.agent import get_last_callable
    # get_last_callable returns the last callable NAME BOUND in the exec env. The
    # entrypoint is bound as an alias of _v95_entrypoint, so the bound name is the
    # wrapper's. Each call re-execs the source, so object identity is not
    # meaningful; assert the bound name is one of the two entrypoint objects and
    # that the bound callable actually applies the overlay.
    bound = get_last_callable(OUT.read_text(), None, str(OUT))
    bound_name = getattr(bound, "__name__", "")
    probe_farm = {"money": 5000, "farmer": [0, 0], "hands": [[3, 3]],
                  "tiles": [[None] * 10 for _ in range(10)]}
    probe_farm["tiles"][3][3] = {"kind": "PLANT", "crop": "STRAWBERRY", "planted_day": 8,
                                 "yield_units": 1, "watered_today": False}
    probe_obs = {"day": 20, "hour": 5, "player": 0, "step": 485,
                 "market": {"prices": {"FERTILIZER": 48, "WHEAT": 25}},
                 "private": {"shed": {"WHEAT": 40}, "inventories": [{"WHEAT": 1}, {"FERTILIZER": 2}], "seeds": {}},
                 "farms": [probe_farm]}
    bound_action = bound(probe_obs, {})
    check("Kaggle loader binds the V95 entrypoint and the overlay runs through it",
          bound_name in ("_v95_entrypoint", "_kaggle_submission_entrypoint")
          and isinstance(bound_action, dict) and "farmer" in bound_action,
          f"bound={bound_name} returned_keys={sorted(bound_action) if isinstance(bound_action, dict) else type(bound_action)}")

    def obs_with(fert, tile, day=20, planted_day=12, yield_units=1, watered=False):
        farm = {"money": 5000, "farmer": [0, 0], "hands": [[3, 3]],
                "tiles": [[None] * 10 for _ in range(10)]}
        if tile is not None:
            farm["tiles"][3][3] = tile
        return {
            "day": day, "hour": 5, "player": 0, "step": day * 24 + 5,
            "market": {"prices": {"FERTILIZER": 48, "STRAWBERRY": 142}},
            # inventories[0] is the farmer (off the ripe tile, nothing to do),
            # inventories[1] is hand 0 which stands on the ripe tile.
            "private": {"shed": {"FERTILIZER": 0},
                        "inventories": [{"WHEAT": 1}, {"FERTILIZER": fert}],
                        "seeds": {}},
            "farms": [farm],
        }

    RIPE = {"kind": "PLANT", "crop": "STRAWBERRY", "planted_day": 8,
            "yield_units": 1, "watered_today": True, "fertilized_until_day": -1}
    # The regression fixture for the measured V95 v1 failure: in-window, carrying
    # yield, but NOT watered today. The engine only pays the fertilizer bonus
    # inside a WATER action, so this must NOT be fertilized.
    DRY = {"kind": "PLANT", "crop": "STRAWBERRY", "planted_day": 8,
           "yield_units": 3, "watered_today": False, "fertilized_until_day": -1}
    # Already fertile: fertilizing again burns the unit for nothing.
    FERT = {"kind": "PLANT", "crop": "STRAWBERRY", "planted_day": 8,
            "yield_units": 2, "watered_today": True, "fertilized_until_day": 99}
    YOUNG = {"kind": "PLANT", "crop": "STRAWBERRY", "planted_day": 18,
             "yield_units": 0, "watered_today": True, "fertilized_until_day": -1}

    base = {"farmer": ["PASS"], "hands": [], "market": [["SELL", "FERTILIZER", 3]]}

    # 1. displaceable PASS on a ripe in-window tile -> FERTILIZE
    out = mod._v95_apply(obs_with(2, RIPE), {**base, "hands": [["PASS"]]})
    check("carrying fert + PASS on ripe in-window tile -> FERTILIZE",
          out.get("hands") == [["FERTILIZE"]], json.dumps(out.get("hands")))

    # 2. no fertilizer in hand -> untouched
    out = mod._v95_apply(obs_with(0, RIPE), {**base, "hands": [["PASS"]]})
    check("no FERTILIZER in hand -> untouched", out.get("hands") == [["PASS"]])

    # 3. protected action never displaced
    for act in (["HARVEST"], ["FEED"], ["PICKUP", "STRAWBERRY", 2], ["EAST"]):
        out = mod._v95_apply(obs_with(2, RIPE), {**base, "hands": [act]})
        check(f"protected action {act[0]} never displaced", out.get("hands") == [act])

    # 4. tile outside the yield window -> untouched (fertilizing would waste it)
    out = mod._v95_apply(obs_with(2, YOUNG, day=12), {**base, "hands": [["PASS"]]})
    check("in-window test: young tile not fertilized", out.get("hands") == [["PASS"]])

    # 4b. REGRESSION: in-window and carrying yield but NOT watered today must not
    # be fertilized. This is the exact case that cost the v1 candidate -6,926/game.
    out = mod._v95_apply(obs_with(2, DRY), {**base, "hands": [["PASS"]]})
    check("REGRESSION: un-watered tile is not fertilized (v1 lost 0W-22L on this)",
          out.get("hands") == [["PASS"]], json.dumps(out.get("hands")))

    # 4c. REGRESSION: an already-fertile tile must not be fertilized again.
    out = mod._v95_apply(obs_with(2, FERT), {**base, "hands": [["PASS"]]})
    check("REGRESSION: already-fertile tile is not re-fertilized",
          out.get("hands") == [["PASS"]], json.dumps(out.get("hands")))

    # 5. non-plant tile -> untouched
    WEED = {"kind": "WEED"}
    out = mod._v95_apply(obs_with(2, WEED), {**base, "hands": [["PASS"]]})
    check("weed tile not fertilized", out.get("hands") == [["PASS"]])

    # 6. market list is never touched
    out = mod._v95_apply(obs_with(2, RIPE), {**base, "hands": [["PASS"]]})
    check("market list untouched", out.get("market") == base["market"], json.dumps(out.get("market")))

    # 7. input action not mutated
    inp = {**base, "hands": [["PASS"]]}
    mod._v95_apply(obs_with(2, RIPE), inp)
    check("input action not mutated", inp["hands"] == [["PASS"]])

    # 8. fail-safe when the observation omits private
    out = mod._v95_apply({"day": 20, "player": 0, "farms": [{"money": 0, "farmer": [0, 0], "hands": [], "tiles": []}]},
                         {**base, "hands": [["PASS"]]})
    check("missing private -> untouched (fail safe)", out.get("hands") == [["PASS"]])

    (HERE / "candidate_build.json").write_text(json.dumps({
        "candidate": str(OUT),
        "sha256": digest,
        "v92_source_sha256": hashlib.sha256(v92_text.encode()).hexdigest(),
        "v92_file_sha256": hashlib.sha256(V92.read_bytes()).hexdigest(),
        "overlay_sha256": hashlib.sha256(OVERLAY.read_bytes()).hexdigest(),
        "checks_passed": len(failures) == 0,
    }, indent=2) + "\n")

    print()
    if failures:
        print(f"FAILED: {failures}")
        raise SystemExit(1)
    print("all candidate self-checks passed")


if __name__ == "__main__":
    main()
